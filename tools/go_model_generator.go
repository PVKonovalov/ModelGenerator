func triggerOptToGoConst(t *model.TriggerOptions) string {
	if t == nil {
		return ""
	}
	var parts []string
	if t.IsDchg() {
		parts = append(parts, "common.TriggerDataChanged")
	}
	if t.IsQchg() {
		parts = append(parts, "common.TriggerQualityChanged")
	}
	if t.IsDupd() {
		parts = append(parts, "common.TriggerDataUpdate")
	}
	if t.IsPeriod() {
		parts = append(parts, "common.TriggerIntegrity")
	}
	if t.IsGI() {
		parts = append(parts, "common.TriggerGI")
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(parts, " | ")
}
